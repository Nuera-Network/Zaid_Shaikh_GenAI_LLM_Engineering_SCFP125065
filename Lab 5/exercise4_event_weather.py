"""Exercise 4: event details -> real weather API -> event recommendation."""

from __future__ import annotations

import json
from datetime import date

from langchain_core.output_parsers import PydanticOutputParser
from langchain_core.prompts import PromptTemplate

from common import extraction_chain, get_llm, source_json, writing_chain
from schemas import EventDetails, WeatherData
from weather_api import fetch_forecast


def event_weather_recommendation(
    event_description_text: str, *, llm=None, weather_fetcher=fetch_forecast
) -> dict:
    if not event_description_text.strip():
        raise ValueError("event_description_text cannot be empty")
    model = llm if llm is not None else get_llm()

    step1 = extraction_chain(
        model,
        EventDetails,
        "Extract event type, date in YYYY-MM-DD format, location, and preference "
        "('indoor', 'outdoor', or 'flexible'). For relative dates, use current "
        "date {today} as the reference. Do not invent missing dates or places. "
        "Event description:\n{event_description_text}",
        ["event_description_text", "today"],
    )
    event = step1.invoke({"event_description_text": event_description_text, "today": date.today().isoformat()})
    # Validate the model's date before making an external API request.
    date.fromisoformat(event.event_date)

    # Step 2 uses a PromptTemplate to construct a query JSON string directly
    # from Step 1. Weather facts are retrieved via API, never generated by LLM.
    weather_query_template = PromptTemplate.from_template(
        '{{"location": {location_json}, "date": {date_json}}}'
    )
    query = json.loads(weather_query_template.format(
        location_json=json.dumps(event.location),
        date_json=json.dumps(event.event_date),
    ))
    api_data = weather_fetcher(query["location"], query["date"])
    weather_parser = PydanticOutputParser(pydantic_object=WeatherData)
    weather = weather_parser.parse(json.dumps(api_data))

    step3 = writing_chain(
        model,
        "You are an event planning assistant. Recommend exactly one of: "
        "proceed as planned, reschedule, or move indoors. Explain briefly "
        "using the supplied weather forecast and the event preference. "
        "Clearly state that a forecast may change. Do not invent weather data.",
        "Event details:\n{event_data}\nForecast:\n{weather_data}\n"
        "Write a concise recommendation to the organizer.",
    )
    recommendation = step3.invoke({
        "event_data": source_json(event),
        "weather_data": source_json(weather),
    })
    return {
        "step1_event_details": event.model_dump(),
        "step2_weather": weather.model_dump(),
        "step3_recommendation": recommendation,
    }


if __name__ == "__main__":
    from datetime import timedelta
    from pprint import pprint

    when = (date.today() + timedelta(days=3)).isoformat()
    pprint(event_weather_recommendation(
        f"Plan an outdoor college cultural event in Pune, India on {when}."
    ))

